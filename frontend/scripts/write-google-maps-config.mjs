import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const key = process.env.GOOGLE_MAPS_API_KEY ?? '';
const outputPath = join(
  process.cwd(),
  'src',
  'app',
  'core',
  'config',
  'google-maps.generated.ts',
);

mkdirSync(dirname(outputPath), { recursive: true });

writeFileSync(
  outputPath,
  `// Auto-generated by scripts/write-google-maps-config.mjs. Do not edit or commit.
export const GOOGLE_MAPS_API_KEY = ${JSON.stringify(key)};
`,
);

if (!key) {
  console.warn('[google-maps] GOOGLE_MAPS_API_KEY is empty. Map page will show setup state.');
}
